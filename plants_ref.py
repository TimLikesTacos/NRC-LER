DOCKET_RE = r"(?<!\d)0?5[02]0{2,6}\s*-?\s*(\d{3})(?!\d)"  # 05000327, 05000 327, 5000-327, 0500000327, 05200025


def unit_name(docket):
    site, unit, _, _ = UNITS[docket]
    name = SITES[site][0]
    if unit == "ISFSI":
        return "%s ISFSI" % name
    return "%s Unit %s" % (name, unit) if unit else name


def load_nrc_operating(path=os.path.join(os.path.dirname(os.path.abspath(__file__)), "nrc_operating_units.tsv")):
    """docket -> dict(owner_operator, region, license) for units on the NRC operating list."""
    if not os.path.exists(path):
        return {}
    with open(path, newline="") as f:
        rows = csv.DictReader((l for l in f if not l.startswith("#")), delimiter="\t")
        return {r["docket"]: r for r in rows}


