def unit_rows():
    nrc = load_nrc_operating()
    for d, (site, unit, typ, vend) in sorted(UNITS.items()):
        n = nrc.get(d, {})
        yield (d, site, unit, unit_name(d), typ, vend, int(d in nrc),
               n.get("owner_operator"), n.get("region"), n.get("license"))


def check():
    nrc = load_nrc_operating()
    bad = [(d, r["name"], r["type"], UNITS.get(d)) for d, r in nrc.items()
           if d not in UNITS or UNITS[d][2] != r["type"]]
    missing_sites = ({u[0] for u in UNITS.values()} | set(ALIASES)) - set(SITES)
    return bad, missing_sites


